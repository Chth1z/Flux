#[test]
fn live_tproxy_default_on_ip_is_normalized_but_nondefault_addresses_fail_closed() {
    for (family, chain, default) in [
        (XtablesRestoreFamily::Ipv4, "FLX4P0000000007", "0.0.0.0"),
        (XtablesRestoreFamily::Ipv6, "FLX6P0000000007", "::"),
    ] {
        let canonical = format!(
            "*mangle\n:{chain} - [0:0]\n-A {chain} -p tcp -j TPROXY --on-port 1536 --tproxy-mark 0x200000/0x600000\nCOMMIT\n"
        );
        let live = format!(
            "*mangle\n:{chain} - [0:0]\n-A {chain} -p tcp -j TPROXY --on-port 1536 --on-ip {default} --tproxy-mark 0x200000/0x600000\nCOMMIT\n"
        );
        assert_eq!(
            project_xtables_save(live.as_bytes(), family).unwrap(),
            project_xtables_save(canonical.as_bytes(), family).unwrap()
        );

        let nondefault = format!(
            "*mangle\n:{chain} - [0:0]\n-A {chain} -p tcp -j TPROXY --on-port 1536 --on-ip 192.0.2.1 --tproxy-mark 0x200000/0x600000\nCOMMIT\n"
        );
        assert_eq!(
            project_xtables_save(nondefault.as_bytes(), family)
                .unwrap_err()
                .kind(),
            XtablesSaveProjectionErrorKind::InvalidOwnedArtifact
        );
    }
}

#[test]
fn save_output_line_count_is_bounded_across_all_tables() {
    let mut exact = "#\n".repeat(MAX_XTABLES_RESTORE_LINES - 4);
    exact.push_str("*filter\nCOMMIT\n*mangle\nCOMMIT\n");
    let projection = project_xtables_save(exact.as_bytes(), XtablesRestoreFamily::Ipv4)
        .expect("maximum full-document line count remains admitted");
    assert!(projection.is_empty());

    let mut oversized = String::from("#\n");
    oversized.push_str(&exact);
    let error = project_xtables_save(oversized.as_bytes(), XtablesRestoreFamily::Ipv4)
        .expect_err("save output above the line limit must fail closed");
    assert_eq!(error.kind(), XtablesSaveProjectionErrorKind::LimitExceeded);
}

fn apply_artifact(bytes: &[u8]) -> XtablesRestoreArtifact {
    parse_xtables_restore(
        bytes,
        XtablesRestoreContext::new(XtablesRestoreAction::Apply, XtablesRestoreFamily::Ipv4),
    )
    .unwrap()
}

fn replacement_artifact(bytes: &[u8]) -> XtablesRestoreArtifact {
    parse_xtables_restore(
        bytes,
        XtablesRestoreContext::new(XtablesRestoreAction::Replace, XtablesRestoreFamily::Ipv4),
    )
    .unwrap()
}

fn rules<'a>(projection: &'a XtablesSaveProjection, chain: &str) -> Vec<&'a str> {
    projection
        .chain(chain)
        .expect("owned chain")
        .rules()
        .iter()
        .map(XtablesOwnedRule::as_str)
        .collect()
}

fn reference<'a>(
    projection: &'a XtablesSaveProjection,
    source: &str,
) -> &'a XtablesNativeReference {
    projection
        .native_references()
        .iter()
        .find(|reference| reference.source_chain() == source)
        .expect("native reference from source")
}
