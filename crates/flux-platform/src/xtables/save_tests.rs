#[test]
fn counter_changes_do_not_change_projection_identity() {
    let first = project_xtables_save(
        b"*mangle\n:FLX4SP - [1:2]\n-A PREROUTING -j FLX4SP\nCOMMIT\n",
        XtablesRestoreFamily::Ipv4,
    )
    .unwrap();
    let second = project_xtables_save(
        b"*mangle\n:FLX4SP - [999:888]\n-A PREROUTING -j FLX4SP\nCOMMIT\n",
        XtablesRestoreFamily::Ipv4,
    )
    .unwrap();
    assert_eq!(first, second);
    assert_eq!(first.digest(), second.digest());
}

#[test]
fn chain_creation_and_emission_order_is_canonical() {
    let first = project_xtables_save(
        br#"*mangle
:FLX4SP - [0:0]
:FLX4SO - [0:0]
:FLX4P0000000007 - [0:0]
:FLX4O0000000007 - [0:0]
-A FLX4SP -j FLX4P0000000007
-A FLX4SO -j FLX4O0000000007
-A PREROUTING -j FLX4SP
-A OUTPUT -j FLX4SO
COMMIT
"#,
        XtablesRestoreFamily::Ipv4,
    )
    .unwrap();
    let reordered = project_xtables_save(
        br#"*mangle
:FLX4O0000000007 - [0:0]
:FLX4P0000000007 - [0:0]
:FLX4SO - [0:0]
:FLX4SP - [0:0]
-A OUTPUT -j FLX4SO
-A FLX4SO -j FLX4O0000000007
-A PREROUTING -j FLX4SP
-A FLX4SP -j FLX4P0000000007
COMMIT
"#,
        XtablesRestoreFamily::Ipv4,
    )
    .unwrap();

    assert_eq!(first, reordered);
    assert_eq!(first.digest(), reordered.digest());
}

#[test]
fn same_chain_rule_order_and_duplicates_remain_material() {
    let first = project_xtables_save(
        br#"*mangle
:FLX4SP - [0:0]
:FLX4P0000000007 - [0:0]
:FLX4F0000000007 - [0:0]
-A FLX4SP -j FLX4P0000000007
-A FLX4SP -j FLX4F0000000007
-A PREROUTING -j FLX4SP
COMMIT
"#,
        XtablesRestoreFamily::Ipv4,
    )
    .unwrap();
    let reordered = project_xtables_save(
        br#"*mangle
:FLX4SP - [0:0]
:FLX4P0000000007 - [0:0]
:FLX4F0000000007 - [0:0]
-A FLX4SP -j FLX4F0000000007
-A FLX4SP -j FLX4P0000000007
-A PREROUTING -j FLX4SP
COMMIT
"#,
        XtablesRestoreFamily::Ipv4,
    )
    .unwrap();
    let duplicated = project_xtables_save(
        br#"*mangle
:FLX4SP - [0:0]
:FLX4P0000000007 - [0:0]
:FLX4F0000000007 - [0:0]
-A FLX4SP -j FLX4P0000000007
-A FLX4SP -j FLX4F0000000007
-A FLX4SP -j FLX4F0000000007
-A PREROUTING -j FLX4SP
COMMIT
"#,
        XtablesRestoreFamily::Ipv4,
    )
    .unwrap();

    assert_ne!(first, reordered);
    assert_ne!(first, duplicated);
    assert_eq!(rules(&duplicated, "FLX4SP").len(), 3);
}

#[test]
fn absolute_hook_ordinal_detects_displacement_by_opaque_rules() {
    let top = project_xtables_save(
        br#"*mangle
:PREROUTING ACCEPT [0:0]
:VENDOR - [0:0]
:FLX4SP - [0:0]
-A PREROUTING -j FLX4SP
-A PREROUTING -m vendor --opaque "ignored syntax" -j VENDOR
COMMIT
"#,
        XtablesRestoreFamily::Ipv4,
    )
    .unwrap();
    let displaced = project_xtables_save(
        br#"*mangle
:PREROUTING ACCEPT [0:0]
:VENDOR - [0:0]
:FLX4SP - [0:0]
-A PREROUTING -m vendor --opaque "ignored syntax" -j VENDOR
-A PREROUTING -j FLX4SP
COMMIT
"#,
        XtablesRestoreFamily::Ipv4,
    )
    .unwrap();

    assert_eq!(reference(&top, "PREROUTING").ordinal().get(), 1);
    assert_eq!(reference(&displaced, "PREROUTING").ordinal().get(), 2);
    assert_ne!(top, displaced);
}

