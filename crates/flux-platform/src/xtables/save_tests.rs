#[test]
fn projection_selects_one_mangle_table_and_ignores_other_tables_opaquely() {
    let input = br#"# Generated by iptables-save v1.8.11
*raw
:PREROUTING ACCEPT [0:0]
-A PREROUTING --opaque "unterminated syntax is irrelevant here
COMMIT
*mangle
:PREROUTING ACCEPT [12:345]
:OUTPUT ACCEPT [7:89]
:VENDOR_CHAIN - [1:2]
:FLX4SP - [3:4]
:FLX4SO - [5:6]
:FLX4P0000000007 - [9:10]
:FLX4O0000000007 - [11:12]
-A PREROUTING -m vendor_unknown --opaque "value with spaces" -j VENDOR_CHAIN
-A FLX4SP -i lo -m mark --mark 0x200000/0x600000 -j FLX4P0000000007
-A FLX4SO -m mark --mark 0x0/0x600000 -j FLX4O0000000007
-A PREROUTING -j FLX4SP
-A OUTPUT -j FLX4SO
COMMIT
*filter
:INPUT ACCEPT [0:0]
COMMIT
# Completed on a test clock
"#;
    let projection = project_xtables_save(input, XtablesRestoreFamily::Ipv4)
        .expect("bounded owned projection from full save document");

    assert_eq!(projection.family(), XtablesRestoreFamily::Ipv4);
    assert!(!projection.is_empty());
    assert_eq!(
        rules(&projection, "FLX4SP"),
        ["-A FLX4SP -i lo -m mark --mark 0x200000/0x600000 -j FLX4P0000000007"]
    );
    assert_eq!(
        rules(&projection, "FLX4SO"),
        ["-A FLX4SO -m mark --mark 0x0/0x600000 -j FLX4O0000000007"]
    );
    assert_eq!(projection.native_references().len(), 2);
    let prerouting = reference(&projection, "PREROUTING");
    assert_eq!(prerouting.ordinal().get(), 2);
    assert_eq!(prerouting.target_chains()[0].as_ref(), "FLX4SP");
    let output = reference(&projection, "OUTPUT");
    assert_eq!(output.ordinal().get(), 1);
    assert_eq!(output.target_chains()[0].as_ref(), "FLX4SO");
}

#[test]
fn missing_or_duplicate_mangle_tables_are_typed() {
    let missing = project_xtables_save(
        b"*filter\n:INPUT ACCEPT [0:0]\nCOMMIT\n",
        XtablesRestoreFamily::Ipv4,
    )
    .expect_err("full save without mangle must remain distinguishable");
    assert_eq!(
        missing.kind(),
        XtablesSaveProjectionErrorKind::MissingMangleTable
    );

    let duplicate = project_xtables_save(
        b"*mangle\nCOMMIT\n*filter\nCOMMIT\n*mangle\nCOMMIT\n",
        XtablesRestoreFamily::Ipv4,
    )
    .expect_err("duplicate mangle snapshot must fail");
    assert_eq!(
        duplicate.kind(),
        XtablesSaveProjectionErrorKind::DuplicateMangleTable
    );
}

