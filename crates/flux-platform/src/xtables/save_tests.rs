#[test]
fn expected_active_state_normalizes_insert_hooks_to_live_append_form() {
    let private = apply_artifact(
        br#"*mangle
:FLX4P0000000007 - [0:0]
:FLX4O0000000007 - [0:0]
-A FLX4P0000000007 -j ACCEPT
-A FLX4O0000000007 -j ACCEPT
COMMIT
"#,
    );
    let stable = apply_artifact(
        br#"*mangle
:FLX4SP - [0:0]
:FLX4SO - [0:0]
-A FLX4SP -i lo -m mark --mark 0x200000/0x600000 -j FLX4P0000000007
-A FLX4SO -m mark --mark 0x0/0x600000 -j FLX4O0000000007
-I PREROUTING -j FLX4SP
-I OUTPUT -j FLX4SO
COMMIT
"#,
    );
    let active = XtablesExpectedState::from_apply_artifacts(
        XtablesRestoreFamily::Ipv4,
        XtablesExpectedStatePhase::Active,
        [&private, &stable],
    )
    .unwrap();
    let output_detached = XtablesExpectedState::from_apply_artifacts(
        XtablesRestoreFamily::Ipv4,
        XtablesExpectedStatePhase::OutputDetached,
        [&private, &stable],
    )
    .unwrap();

    let observed_active = project_xtables_save(
        br#"*mangle
:FLX4SO - [8:9]
:FLX4O0000000007 - [1:2]
:FLX4SP - [3:4]
:FLX4P0000000007 - [5:6]
-A PREROUTING -j FLX4SP
-A OUTPUT -j FLX4SO
-A FLX4SO -m mark --mark 0x0/0x600000 -j FLX4O0000000007
-A FLX4SP -i lo -m mark --mark 0x200000/0x600000 -j FLX4P0000000007
-A FLX4O0000000007 -j ACCEPT
-A FLX4P0000000007 -j ACCEPT
COMMIT
"#,
        XtablesRestoreFamily::Ipv4,
    )
    .unwrap();
    let observed_detached = project_xtables_save(
        br#"*mangle
:FLX4SO - [0:0]
:FLX4O0000000007 - [0:0]
:FLX4SP - [0:0]
:FLX4P0000000007 - [0:0]
-A PREROUTING -j FLX4SP
-A FLX4SO -m mark --mark 0x0/0x600000 -j FLX4O0000000007
-A FLX4SP -i lo -m mark --mark 0x200000/0x600000 -j FLX4P0000000007
-A FLX4O0000000007 -j ACCEPT
-A FLX4P0000000007 -j ACCEPT
COMMIT
"#,
        XtablesRestoreFamily::Ipv4,
    )
    .unwrap();

    assert_eq!(active.phase(), XtablesExpectedStatePhase::Active);
    assert!(active.is_satisfied_by(&observed_active));
    assert!(!active.is_satisfied_by(&observed_detached));
    assert!(output_detached.is_satisfied_by(&observed_detached));
    assert!(
        active
            .projection()
            .native_references()
            .iter()
            .all(|reference| reference.rule().as_str().starts_with("-A "))
    );
}

